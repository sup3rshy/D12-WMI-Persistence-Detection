#!/usr/bin/env python3
"""Render reports/poc-dryrun/summary.md from the dry-run JSON evidence."""
from __future__ import annotations

import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRY = ROOT / "reports" / "poc-dryrun"


def payload(config: dict) -> str:
    props = config.get("ConsumerProperties") or {}
    if "CommandLineTemplate" in props:
        text = props["CommandLineTemplate"]
        if "-EncodedCommand" in text:
            encoded = text.split("-EncodedCommand", 1)[1].strip().split()[0]
            try:
                decoded = base64.b64decode(encoded).decode("utf-16le")
                return f"`{text}` [decoded: {decoded}]"
            except Exception:
                pass
        return f"`{text}`"
    if "ScriptText" in props:
        text = " / ".join(line.strip() for line in props["ScriptText"].splitlines() if line.strip())
        return f"`{text}`"
    return ""


def main() -> None:
    rows = []
    for variant in ("V1", "V2", "V3", "V4", "V5"):
        data = json.loads((DRY / f"{variant}.json").read_text(encoding="utf-8-sig"))
        cfg = data["config"]
        rows.append(
            "| {v} | `{ns}` | `{ev}` | `{cls}` | {filt} | `{query}` | {timer} ms | {payload} |".format(
                v=variant,
                ns=cfg["Namespace"],
                ev=cfg["EventNamespace"],
                cls=cfg["ConsumerClass"],
                filt=cfg["FilterName"],
                query=cfg["Query"],
                timer=cfg["TimerIntervalMs"],
                payload=payload(cfg),
            )
        )

    text = "\n".join(
        [
            "# PoC variants - dry-run configuration",
            "",
            "Generated by `poc/render_dryrun_summary.py` from the JSON written by",
            "`Invoke-WmiSubscription.ps1 -Action Create -DryRun` for each variant.",
            "No WMI object is created by the dry-run. Real execution requires a snapshot VM.",
            "",
            "| Variant | Namespace | Event ns | Consumer | Filter name | Trigger | Timer | Payload |",
            "|---|---|---|---|---|---|---:|---|",
            *rows,
            "",
            "## Safety note",
            "",
            "All payloads write the text marker `NT230-D12-MARKER` to a lab path.",
            "V5 in the dataset contains an inert TEST-NET-2 URL; the runnable PoC V5 is a",
            "VBScript marker write.",
            "",
        ]
    )
    (DRY / "summary.md").write_text(text, encoding="utf-8")
    print(f"wrote {DRY / 'summary.md'}")


if __name__ == "__main__":
    main()
